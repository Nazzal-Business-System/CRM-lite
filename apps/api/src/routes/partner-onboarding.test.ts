import assert from "node:assert/strict";
import test from "node:test";
import express from "express";
import type { AddressInfo } from "node:net";
import { PERMISSION_KEYS as P, type AuthUser } from "@nbs/shared";
import { usersRouter } from "./users";
import { rolesRouter } from "./roles";
import { marketRequestContext } from "../lib/market-context";
import { errorHandler } from "../middleware/error-handler";
import { installMarketStore } from "../test/market-store";
import { env } from "../env";
test("partner user API enforces onboarding authorization, returns defaults, and never exposes passwords", async t => {
  assert.equal(new URL(env.DATABASE_URL).port, "1"); env.MARKET_ACCESS_MODE = "enforced";
  const f = installMarketStore(t); for (const role of f.tables.role!) role.permissions = [];
  let actor: AuthUser | undefined;
  const admin = { id: "admin", role: { id: "admin-role", name: "Admin", isSystem: true }, permissions: [P.USERS_CREATE, P.USERS_UPDATE, P.USERS_VIEW, P.MARKETS_MANAGE_MEMBERSHIPS] } as AuthUser;
  const app = express(); app.use(express.json(), marketRequestContext, (req, _res, next) => { req.authUser = actor; next(); }); app.use("/users", usersRouter); app.use("/roles", rolesRouter); app.use(errorHandler);
  const server = app.listen(0, "127.0.0.1"); await new Promise<void>(resolve => server.once("listening", resolve)); t.after(() => new Promise<void>(resolve => server.close(() => resolve())));
  const origin = `http://127.0.0.1:${(server.address() as AddressInfo).port}`;
  const body = { name: "HTTP Fixture", email: "http@example.invalid", password: "fixture-password-strong", roleId: "sales-role", accountType: "PARTNER", marketCodes: ["JO", "UK"], defaultMarketCode: "UK" };
  const send = (path = "/users", method = "POST", value: unknown = body) => fetch(origin + path, { method, headers: { "Content-Type": "application/json" }, ...(method !== "GET" ? { body: JSON.stringify(value) } : {}) });
  const before = f.tables.user!.length; assert.equal((await send()).status, 401);
  actor = { ...admin, role: { ...admin.role, name: "Sales" } }; assert.equal((await send()).status, 403); assert.equal(f.tables.user!.length, before);
  actor = admin; assert.equal((await send("/users", "POST", { ...body, marketCodes: [], defaultMarketCode: null })).status, 400); assert.equal(f.tables.user!.length, before);
  const created = await send(); assert.equal(created.status, 201);
  const text = await created.text(); assert.ok(!text.includes(body.password)); assert.ok(!text.includes("passwordHash")); const user = JSON.parse(text).data.user;
  assert.equal(user.accountType, "PARTNER"); assert.equal(user.initialDisplayCurrency, "GBP"); assert.equal(user.defaultMarketCode, "UK"); assert.deepEqual(user.marketCodes.sort(), ["JO", "UK"]);
  assert.equal((await send(`/users/${user.id}`, "GET")).status, 200);
  actor = { ...admin, permissions: [P.USERS_UPDATE] }; assert.equal((await send(`/users/${user.id}`, "PATCH", { marketCodes: ["US"], defaultMarketCode: "US" })).status, 403);
  assert.equal(f.tables.user!.find(row => row.id === user.id)!.defaultMarketCode, "UK");
  const priceBookAccess = { scope: "selected", bookIds: ["JO"], defaultBookId: "JO" };
  actor = admin;
  assert.equal((await send(`/users/${user.id}`, "PATCH", { priceBookAccess })).status, 403);
  const count = f.tables.user!.length;
  assert.equal((await send("/users", "POST", { ...body, email: "book-denied@example.invalid", priceBookAccess })).status, 403);
  assert.equal(f.tables.user!.length, count);
  actor = { ...admin, permissions: [...admin.permissions, P.PRICING_PRICEBOOKS_MANAGE] };
  assert.equal((await send(`/users/${user.id}`, "PATCH", { priceBookAccess: { ...priceBookAccess, defaultBookId: "US" } })).status, 400);
  assert.equal((await send(`/users/${user.id}`, "PATCH", { priceBookAccess })).status, 200);
  assert.deepEqual(f.tables.priceBookGrant!.filter(row => row.userId === user.id).map(row => row.bookId), ["JO"]);
  assert.equal(f.tables.userPricingPreference!.find(row => row.userId === user.id)!.defaultBookId, "JO");
  const explicitCreate = await send("/users", "POST", { ...body, email: "explicit-books@example.invalid", priceBookAccess });
  assert.equal(explicitCreate.status, 201);
  const createdId = (await explicitCreate.json() as { data: { user: { id: string } } }).data.user.id;
  assert.equal(f.tables.priceBookGrant!.filter(row => row.userId === createdId).length, 1);
  f.tables.role!.find(row => row.id === "sales-role")!.permissions = [{ permission: { key: P.PRICING_VIEW } }];
  const options = await send("/roles/options", "GET"); assert.equal(options.status, 200);
  const optionData = await options.json() as { data: { roles: Array<{ id: string; permissionKeys: string[] }> } };
  assert.deepEqual(optionData.data.roles.find(role => role.id === "sales-role")!.permissionKeys, [P.PRICING_VIEW]);
});
