import assert from "node:assert/strict";
import test from "node:test";
import type { AddressInfo } from "node:net";
import express from "express";
import { PERMISSION_KEYS, type AuthUser } from "@nbs/shared";
import { marketRequestContext } from "../lib/market-context";
import { prisma } from "../lib/prisma";
import { env } from "../env";
import { marketMembershipsRouter } from "./market-memberships";
import { companiesRouter } from "./companies";
import { errorHandler } from "../middleware/error-handler";
import { installMarketStore } from "../test/market-store";

test("HTTP membership authorization, payload validation, removal, and 503 recovery are server-enforced", async (t) => {
  env.MARKET_ACCESS_MODE = "enforced";
  const f = installMarketStore(t);
  let identity: AuthUser | undefined;
  const makeActor = (admin: boolean, permissions: string[]) => ({ id: admin ? "admin" : "partner", role: { id: admin ? "admin-role" : "sales-role", name: admin ? "Admin" : "Sales", isSystem: true }, permissions }) as AuthUser;
  const admin = makeActor(true, [PERMISSION_KEYS.MARKETS_MANAGE_MEMBERSHIPS]);
  const app = express();
  app.use(express.json(), marketRequestContext);
  // Trusted fixture identity only. The real route's requireAuth/requirePermission still execute.
  app.use((req, _res, next) => { req.authUser = identity; next(); });
  app.use("/admin", marketMembershipsRouter);
  app.use("/companies", companiesRouter);
  app.use(errorHandler);
  const server = app.listen(0, "127.0.0.1");
  await new Promise<void>((resolve) => server.once("listening", resolve));
  t.after(() => new Promise<void>((resolve) => server.close(() => resolve())));
  const base = `http://127.0.0.1:${(server.address() as AddressInfo).port}`;
  const get = () => fetch(`${base}/admin/users/partner/markets`);
  assert.equal((await get()).status, 401);
  identity = makeActor(false, [PERMISSION_KEYS.MARKETS_MANAGE_MEMBERSHIPS]);
  assert.equal((await get()).status, 403);
  identity = makeActor(true, []); assert.equal((await get()).status, 403);
  identity = admin;
  const response = await get(); assert.equal(response.status, 200);
  const body = await response.json() as { data: { memberships: unknown[] } };
  assert.equal(body.data.memberships.length, 2);
  assert.equal(/tokenHash|passwordHash/.test(JSON.stringify(body)), false);
  const put = (marketCodes: string[]) => fetch(`${base}/admin/users/partner/markets`, { method: "PUT", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ marketCodes }) });
  assert.equal((await put(["JO", "jo"])).status, 400);
  assert.equal((await put(["UNKNOWN"])).status, 400);
  assert.equal((await put([])).status, 200);
  identity = makeActor(false, [PERMISSION_KEYS.COMPANIES_VIEW]);
  const count = await import("../lib/market-context");
  assert.equal(await count.marketContext.run({ actor: () => identity }, () => prisma.company.count()), 0);
  f.setOutage(true);
  assert.equal((await fetch(`${base}/companies`)).status, 503);
  identity = admin;
  assert.equal((await get()).status, 503);
  f.setOutage(false);
  assert.equal((await get()).status, 200);
  identity = makeActor(false, [PERMISSION_KEYS.COMPANIES_VIEW]);
  assert.equal((await fetch(`${base}/companies`)).status, 200);
});
